#!/usr/bin/env python3
"""Turn .fd files into a Go table of LVO -> function name (developer tool).

usage: fdnames.py exec_lib.fd dos_lib.fd ... > internal/amiga/fdnames.go
"""
import os, re, sys
print("// Code generated by tools/fdnames.py from the NDK .fd files; DO NOT EDIT.\n")
print("package amiga\n")
print("// fdNames maps library name -> negative LVO offset -> function name.")
print("var fdNames = map[string]map[int]string{")
for path in sys.argv[1:]:
    lib = os.path.basename(path).replace("_lib.fd", ".library")
    bias, public, out = 0, True, []
    for line in open(path, encoding="latin-1"):
        line = line.strip()
        if line.startswith("##bias"): bias = int(line.split()[1])
        elif line.startswith("##private"): public = False
        elif line.startswith("##public"): public = True
        elif line.startswith("##") or line.startswith("*") or not line: continue
        else:
            m = re.match(r"(\w+)\(", line)
            if m: out.append((bias, m.group(1) if public else "private" + m.group(1))); bias += 6
    print('\t"%s": {' % lib)
    for b, n in out: print("\t\t%d: \"%s\"," % (b, n))
    print("\t},")
print("}")
